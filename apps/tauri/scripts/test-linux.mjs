// The Tauri app's desktop tests (tests/e2e/tauri.spec.ts) on Linux, from any
// computer with Podman: in a container (linux/Containerfile) with WebKitGTK and a
// display of its own, the checkout copied in (as it is, uncommitted changes
// too), installed, staged, built for the tests, and tested. What it builds and
// downloads is kept in Podman volumes, so a second run is quick.
//
//   node apps/tauri/scripts/test-linux.mjs                 build and test
//   node apps/tauri/scripts/test-linux.mjs -- -g "joins"   with Playwright's arguments
//   node apps/tauri/scripts/test-linux.mjs --shell         a shell in the container instead
//
// A Podman machine with little memory (2 GB, as made by default, and shared with
// whatever else runs in it) builds the app unoptimised, one job at a time.
import { execFileSync, spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import { argv, env, exit, stderr } from 'node:process';

const ROOT = resolve(import.meta.dirname, '../../..');
const IMAGE = 'kuraa-tauri-linux';
const split = argv.indexOf('--');
const own = split < 0 ? argv.slice(2) : argv.slice(2, split);
const playwright = split < 0 ? [] : argv.slice(split + 1);
const quote = (a) => `'${a.replace(/'/g, `'\\''`)}'`;

execFileSync('podman', ['build', '-t', IMAGE, '-f', resolve(import.meta.dirname, '../linux/Containerfile'), resolve(import.meta.dirname, '../linux')], { stdio: 'inherit' });

// Copied in, without what each side builds or installs for itself (kept in the volume between runs).
const EXCLUDE = ['.git', 'node_modules', 'dist', 'test-results', 'playwright-report', '.dev-workspaces', '.claude', 'apps/desktop/build', 'apps/desktop/vendor', 'apps/tauri/build', 'apps/tauri/src-tauri/target', 'apps/tauri/src-tauri/staged', 'apps/tauri/src-tauri/binaries', 'apps/tauri/src-tauri/gen', 'apps/tauri/src-tauri/permissions/autogenerated'];
const steps = [
  'set -e',
  `rsync -a --delete ${EXCLUDE.map((e) => `--exclude=${quote(`/${e}`)}`).join(' ')} --exclude=node_modules /src/ /work/repo/`,
  'cd /work/repo',
  'pnpm config set store-dir /work/pnpm-store >/dev/null',
  'pnpm install --frozen-lockfile',
  'git config --global user.name "kuraa CI"',
  'git config --global user.email "ci@kuraa.invalid"',
  'pnpm --filter @kuraa/tauri gather',
  'node apps/tauri/scripts/build.mjs --test',
  // Its window, on the container's own display (no one's screen): shown, so the webview runs as it would for someone.
  `dbus-run-session -- xvfb-run -a -s "-screen 0 1440x900x24" pnpm test:e2e --project tauri ${playwright.map(quote).join(' ')}`,
];
const run = spawnSync(
  'podman',
  [
    // One at a time: a run still going (its terminal closed) is replaced, never run beside (they share the volume).
    'run', '--rm', '-i', '--name', 'kuraa-tauri-linux', '--replace', ...(own.includes('--shell') ? ['-t'] : []),
    '-v', `${ROOT}:/src:ro`,
    '-v', 'kuraa-tauri-linux-work:/work',
    '-v', 'kuraa-tauri-linux-cargo:/usr/local/cargo/registry',
    '-e', 'KURAA_TAURI_BUILT=1',
    // DEBUG=1: the app's output, as the tests run.
    ...(env.DEBUG ? ['-e', `DEBUG=${env.DEBUG}`] : []),
    '-e', 'KURAA_SHOW_WINDOWS=1',
    '-e', 'KURAA_RENDER_TOOLS=/work/render-tools',
    '-e', 'ELECTRON_SKIP_BINARY_DOWNLOAD=1',
    '-e', 'CI=true',
    // WebKitGTK without a GPU.
    '-e', 'WEBKIT_DISABLE_COMPOSITING_MODE=1',
    '-e', 'WEBKIT_DISABLE_DMABUF_RENDERER=1',
    // Little memory (and shared, with other checkouts' containers): not optimised, no link-time optimisation, one job
    // at a time (KURAA_LINUX_JOBS for more). The tests need no fast program.
    '-e', 'CARGO_PROFILE_RELEASE_OPT_LEVEL=0',
    '-e', 'CARGO_PROFILE_RELEASE_LTO=false',
    '-e', 'CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16',
    '-e', `CARGO_BUILD_JOBS=${env.KURAA_LINUX_JOBS ?? '1'}`,
    IMAGE,
    'bash', '-c', own.includes('--shell') ? `${steps.slice(0, 3).join(' && ')} && exec bash` : steps.join('\n'),
  ],
  { stdio: 'inherit' },
);
if (run.signal || run.status === 137) stderr.write(`test-linux: the container was stopped (${run.signal ?? 'killed'}): out of memory? Give the Podman machine more (podman machine set --memory 4096) or build with fewer jobs.\n`);
exit(run.status ?? 1);
