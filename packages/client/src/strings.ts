// Every word the client shows, in one place (decision 0044): English for now,
// laid out to be translated later. Plain strings, and functions for those that
// take values. Vue templates and the plain-DOM code (ask.ts, nodeviews.ts,
// runs.ts) read them from here. No framework: a translation would be another
// object of the same shape.
//
// The words: a document is *saved* (written to its file, and kept in its
// history as a *version*); a workspace has an *online copy* and other
// *devices*; the app talks to a *host* with an *access code*. Commit ids,
// branch names and command-line flags stay behind a "Details" disclosure.
// Spelling is British, as in the docs.
import { keyLabel } from './keys.js';

const rules = new Intl.PluralRules('en');

/** A count with its noun: count(3, 'file', 'files') → '3 files'. */
export function count(n: number, one: string, other: string): string {
  return `${n.toLocaleString()} ${rules.select(n) === 'one' ? one : other}`;
}

/** The noun alone, for a count shown elsewhere: plural(1, 'change', 'changes') → 'change'. */
export function plural(n: number, one: string, other: string): string {
  return rules.select(n) === 'one' ? one : other;
}

/** A list in words: 'a, b and c'. */
export function listOf(items: string[]): string {
  return new Intl.ListFormat('en', { style: 'long', type: 'conjunction' }).format(items);
}

const quote = (s: string) => `“${s}”`;
const dateTime = (d: Date | string) => new Date(d).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' });

/** Names as words: "Ada", "Ada and Bo", "Ada, Bo and Cy". */
const list = (names: string[]) => (names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} and ${names.at(-1)}`);

